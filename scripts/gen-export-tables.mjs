#!/usr/bin/env node
/**
 * Generate (or check) the export tables in each package README.
 *
 * Usage:
 *   node scripts/gen-export-tables.mjs           # rewrite tables in place
 *   node scripts/gen-export-tables.mjs --check   # exit 1 if any README is stale
 *
 * The tables (one per public entry: `@openwizard/core`, `@openwizard/core/testing`, …)
 * live between `<!-- exports:start -->` and `<!-- exports:end -->` markers in
 * `packages/<pkg>/README.md`. Missing markers are appended at the end.
 * v1's docs drifted from the code because tables were hand-maintained; this
 * makes the code the source of truth.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { collectExports, listPackages, ROOT } from './lib/exports.mjs'

const START = '<!-- exports:start -->'
const END = '<!-- exports:end -->'
const check = process.argv.includes('--check')

let stale = false

for (const pkg of listPackages()) {
  const readmePath = join(pkg.dir, 'README.md')
  const sections = []
  let total = 0
  for (const entry of pkg.entries) {
    const exportsInfo = collectExports(entry.indexPath)
    total += exportsInfo.length
    const rows = exportsInfo.map((e) => {
      const link = e.file
        ? `[src](../../${relative(ROOT, e.file).replaceAll('\\', '/')}#L${e.line})`
        : ''
      return `| \`${e.name}\` | ${e.kind} | ${escapePipes(e.summary) || '—'} | ${link} |`
    })
    sections.push(
      ...(pkg.entries.length > 1 ? [`### \`${entry.specifier}\``, ''] : []),
      `| Export | Kind | Summary | Source |`,
      `|---|---|---|---|`,
      ...rows,
      '',
    )
  }
  const table = [
    START,
    '',
    `<!-- generated by scripts/gen-export-tables.mjs — do not edit by hand -->`,
    '',
    ...sections,
    END,
  ].join('\n')

  const existing = existsSync(readmePath) ? readFileSync(readmePath, 'utf8') : `# ${pkg.name}\n`
  const startIdx = existing.indexOf(START)
  const endIdx = existing.indexOf(END)
  let next
  if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
    next = existing.slice(0, startIdx) + table + existing.slice(endIdx + END.length)
  } else {
    next = `${existing.trimEnd()}\n\n## Exports\n\n${table}\n`
  }
  if (normalize(next) !== normalize(existing)) {
    stale = true
    if (check) {
      console.error(`[export-tables] ${relative(ROOT, readmePath)} is stale. Run: pnpm docs:gen`)
    } else {
      writeFileSync(readmePath, next)
      console.log(`[export-tables] updated ${relative(ROOT, readmePath)} (${total} exports)`)
    }
  } else if (!check) {
    console.log(`[export-tables] ${relative(ROOT, readmePath)} up to date (${total} exports)`)
  }
}

if (check && stale) process.exit(1)
if (check) console.log('[export-tables] all README export tables are up to date')

function escapePipes(s) {
  return s.replaceAll('|', '\\|')
}
function normalize(s) {
  return s.replaceAll('\r\n', '\n').trimEnd()
}
